root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else
                    pathlib.Path(__file__).resolve().parents[2] / "retrohub/frontend/node_modules/lucide-react")
icons_dir = root / "dist/esm/icons"
version = re.search(r'"version":\s*"([^"]+)"', (root / "package.json").read_text()).group(1)


def num(value: str) -> float:
    return float(value)


def fmt(value: float) -> str:
    return f"{value:g}"


def to_path(tag: str, attrs: dict) -> str:
    if tag == "path":
        return attrs["d"]
    if tag == "line":
        return f"M{attrs['x1']} {attrs['y1']}L{attrs['x2']} {attrs['y2']}"
    if tag in ("polyline", "polygon"):
        points = re.split(r"[\s,]+", attrs["points"].strip())
        pairs = [f"{points[i]} {points[i + 1]}" for i in range(0, len(points), 2)]
        return "M" + "L".join(pairs) + ("Z" if tag == "polygon" else "")
    if tag in ("circle", "ellipse"):
        cx, cy = num(attrs["cx"]), num(attrs["cy"])
        rx = num(attrs.get("r", attrs.get("rx", "0")))
        ry = num(attrs.get("r", attrs.get("ry", "0")))
        return (f"M{fmt(cx - rx)} {fmt(cy)}a{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(2 * rx)} 0"
                f"a{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(-2 * rx)} 0Z")
    if tag == "rect":
        x, y = num(attrs.get("x", "0")), num(attrs.get("y", "0"))
        w, h = num(attrs["width"]), num(attrs["height"])
        rx = num(attrs.get("rx", attrs.get("ry", "0")))
        ry = num(attrs.get("ry", attrs.get("rx", "0")))
        if rx == 0:
            return f"M{fmt(x)} {fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}Z"
        return (f"M{fmt(x + rx)} {fmt(y)}h{fmt(w - 2 * rx)}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(rx)} {fmt(ry)}"
                f"v{fmt(h - 2 * ry)}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(-rx)} {fmt(ry)}h{fmt(-(w - 2 * rx))}"
                f"a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(-rx)} {fmt(-ry)}v{fmt(-(h - 2 * ry))}"
                f"a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(rx)} {fmt(-ry)}Z")
    raise ValueError(f"unsupported SVG element: {tag}")


def parse(name: str) -> list[str]:
    source = (icons_dir / f"{name}.mjs").read_text()
    alias = re.search(r"export \{ default \} from '\./([\w-]+)\.mjs'", source)
    if alias:
        return parse(alias.group(1))
    paths = []
    for tag, body in re.findall(r'\[\s*"(\w+)",\s*\{(.*?)\}\s*\]', source, re.S):
        attrs = dict(re.findall(r'(\w+):\s*"([^"]*)"', body))
        attrs.pop("key", None)
        paths.append(to_path(tag, attrs))
    if not paths:
        raise ValueError(f"empty icon: {name}")
    return paths


def camel(name: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[-]", name))


out = [
    "// Generated by scripts/gen-icons.py from lucide-react " + version + ": do not edit by hand.",
    "// Lucide icons, ISC license (https://lucide.dev, see docs/licenses.md).",
    "package ovh.verbois.retrohub.ui.icons",
    "",
    "import androidx.compose.ui.graphics.vector.ImageVector",
    "",
    "object Lucide {",
]
for name in ICONS:
    data = ", ".join('"' + p.replace('"', '\\"') + '"' for p in parse(name))
    out.append(f"    val {camel(name)}: ImageVector by lazy {{ lucide(\"{name}\", {data}) }}")
out.append("}")
target = pathlib.Path(__file__).resolve().parents[1] / "shared/src/commonMain/kotlin/ovh/verbois/retrohub/ui/icons/LucideIcons.kt"
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text("\n".join(out) + "\n")
print(f"{len(ICONS)} icons written to {target}")
